#include <iostream>
using namespace std;

int main()
{

    /*
    
    All c++ variables must be identified by unique names.
    The identifier is the name of the variable.

    These unique names are called identifiers.

    It's recommended to use descriptive names in order to create understandable and maintainable code.
    
    */

    /*
    
     The general rules for naming a variable :

     a variable in c++ only contains letters , numbers and underscores.
     a variable is a case-sensitive.
     you must begin with letter or underscore.
     don't use reserved words.
    
    */

    int Age = 30;

    /*

       int : Data type
       Age : Identifier
       30  : Literal

    */

    /*
    
     Constants : when you don't want others to override existing variables values ,
     use the const keyword it means this varibale unchangable and read only.
    
    */

    float const PI = 3.14;

    return 0;
}
