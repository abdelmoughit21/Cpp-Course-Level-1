#include <iostream>
using namespace std;

int main()
{

    /*
    
     *  : Multiplication
     +  : Addition
     -  : Substraction
     /  : Division

     */

    int A = 50, B = 20;

    cout << A + B << endl;
    cout << A - B << endl;
    cout << A * B << endl;
    cout << A / B << endl;

    return 0;
}