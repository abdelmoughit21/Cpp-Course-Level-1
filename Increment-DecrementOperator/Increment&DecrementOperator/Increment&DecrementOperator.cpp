#include <iostream>
using namespace std;


int main()
{

    /*
    
      A++ will increase A by one.
      A-- will increase B by one.

      the same thing for this :

      ++A will increase A by one.
      --A will increase B by one.

    */

    int A = 10;

    A++;
    cout << A << endl;

    ++A;
    cout << A << endl;

    A--;
    cout << A << endl;

    --A;
    cout << A << endl;

    return 0;
}
